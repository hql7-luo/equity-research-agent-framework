"""Behavioral artifact tests: compare committed LLM outputs to the oracle.

These tests validate the *committed artifacts* of behavioral runs with
tolerance-based numerical comparison. They do not rerun an LLM and do not
prove future runtime behavior. Files are regenerated by running a capable
model against tests/fixtures/ (inputs only) plus SKILL.md or the standalone
Prompt; tests/oracle.py (expected values) is never supplied to the model.

Outputs are committed so CI can check them deterministically. To mark a
fresh behavioral run, delete the files in tests/outputs/ and regenerate.
"""

import math
import re
import unittest
from pathlib import Path

from oracle import expected_values

ROOT = Path(__file__).resolve().parents[1]
OUTPUTS = ROOT / "tests" / "outputs"
TOL = 0.005  # 0.5% relative tolerance for model-reported numbers

FULL = OUTPUTS / "full-en.md"
QUICK_ZH = OUTPUTS / "quick-zh.md"
MISSING = OUTPUTS / "missing-data.md"
STANDALONE = OUTPUTS / "standalone-quick-en.md"


def numbers_in(text: str) -> list[float]:
    return [float(x.replace(",", "")) for x in re.findall(r"\d[\d,]*\.\d+", text)]


@unittest.skipUnless(FULL.is_file(), "behavioral outputs not generated; run the fixture through a model first")
class FullResearchOutputTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.text = FULL.read_text(encoding="utf-8")

    def test_nine_sections_and_all_agents(self):
        for number in range(1, 10):
            self.assertRegex(self.text, rf"(?m)^## {number}\.")
        for letter in "ABCDEFG":
            self.assertIn(f"Agent {letter}", self.text)
        self.assertIn("Manager", self.text)

    def test_scenario_values_match_oracle_within_tolerance(self):
        reported = numbers_in(self.text)
        for name, result in expected_values().items():
            expected = result["per_share"]
            self.assertTrue(
                any(math.isclose(v, expected, rel_tol=TOL) for v in reported),
                f"{name} value {expected:.4f} not found within {TOL:.1%} tolerance in report",
            )

    def test_terminal_economics_explained(self):
        self.assertRegex(self.text, r"(?i)terminal NOPAT")
        self.assertRegex(self.text, r"(?i)reinvestment")

    def test_mos_is_justified_and_cross_checked(self):
        # Haircut must be stated, within the methodology's 10%-45% bands,
        # arithmetically consistent with the reported Base value and price,
        # and cross-checked against Bear value.
        m = re.search(r"(?i)(\d{1,2}(?:\.\d+)?)\s*%\s*(?:margin-of-safety|safety) (?:haircut|discount)", self.text)
        self.assertIsNotNone(m, "report must state its margin-of-safety haircut explicitly")
        haircut = float(m.group(1)) / 100
        self.assertGreaterEqual(haircut, 0.10)
        self.assertLessEqual(haircut, 0.45)
        base = expected_values()["Base"]["per_share"]
        reported = numbers_in(self.text)
        implied_price = base * (1 - haircut)
        self.assertTrue(
            any(math.isclose(v, implied_price, rel_tol=0.02) for v in reported),
            f"buy price {implied_price:.4f} (Base x (1 - {haircut})) not found in report",
        )
        bear = expected_values()["Bear"]["per_share"]
        self.assertTrue(any(math.isclose(v, bear, rel_tol=TOL) for v in reported))
        self.assertRegex(self.text, r"(?i)not a guaranteed floor|no guaranteed|does not guarantee")

    def test_evidence_labels_and_honesty(self):
        self.assertIn("Verified Fact (Hypothetical", self.text)
        self.assertIn("Modeling Assumption (Hypothetical", self.text)
        self.assertIn("Unavailable Information", self.text)
        self.assertRegex(self.text, r"(?i)simulated|one model|not independent")
        self.assertNotIn("Medium-Low", self.text)


@unittest.skipUnless(QUICK_ZH.is_file(), "behavioral outputs not generated")
class QuickPriceTests(unittest.TestCase):
    def test_quick_zh_exactly_two_lines_and_consistent(self):
        lines = QUICK_ZH.read_text(encoding="utf-8").splitlines()
        self.assertEqual(len(lines), 2)
        self.assertTrue(lines[0].startswith("1. **"))
        self.assertTrue(lines[1].startswith("2. **"))
        self.assertRegex("".join(lines), r"[\u4e00-\u9fff]")
        price = numbers_in(lines[0])
        self.assertEqual(len(price), 1, "line 1 must contain exactly one price")
        base = expected_values()["Base"]["per_share"]
        # Haircut must be in the allowed bands and arithmetic must be consistent
        h_candidates = [h for h in (x / 100 for x in range(10, 46))
                        if math.isclose(base * (1 - h), price[0], rel_tol=0.02)]
        self.assertTrue(h_candidates,
                        f"price {price[0]} inconsistent with oracle Base {base:.4f} under any 10-45% haircut")
        self.assertTrue(any(math.isclose(v, base, rel_tol=0.02) for v in numbers_in(lines[1])),
                        "line 2 must state the Base intrinsic value")

    def test_standalone_prompt_quick_en(self):
        if not STANDALONE.is_file():
            self.skipTest("standalone output not generated")
        lines = STANDALONE.read_text(encoding="utf-8").splitlines()
        self.assertEqual(len(lines), 2)
        self.assertTrue(lines[0].startswith("1. **Margin-of-Safety Buy Price:**"))
        price = numbers_in(lines[0])
        self.assertEqual(len(price), 1)
        base = expected_values()["Base"]["per_share"]
        ok = any(math.isclose(base * (1 - h / 100), price[0], rel_tol=0.02) for h in range(10, 46))
        self.assertTrue(ok, "standalone price inconsistent with oracle")


@unittest.skipUnless(MISSING.is_file(), "behavioral outputs not generated")
class MissingDataTests(unittest.TestCase):
    def test_refusal_is_concise_and_fabrication_free(self):
        text = MISSING.read_text(encoding="utf-8")
        self.assertLessEqual(len([l for l in text.splitlines() if l.strip()]), 3)
        self.assertRegex(text, r"(?i)cannot|unable|insufficient")
        # No fabricated valuation numbers (allow only the year/date-like tokens)
        self.assertNotRegex(text, r"(?i)(price|value)[^\n]*\d+\.\d{2}")
        self.assertNotIn("Northstar", text)


if __name__ == "__main__":
    unittest.main(verbosity=2)
